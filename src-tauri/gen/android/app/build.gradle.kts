// Release signing (.claude/rules/android.md, docs/adr/0015). The keystore is NEVER committed:
// values are read from `keystore.properties` (gitignored, local dev) and fall back to the
// ANDROID_* environment variables (CI). If neither is configured the release build simply stays
// unsigned instead of failing, so an unsigned `assembleRelease` is still usable for size checks.
// NOTE: this file is generated by the Tauri CLI. If the android project is ever re-initialised,
// re-apply this block and the `signingConfig` line in the release buildType.
val keystoreProperties = Properties().apply {
    val propFile = file("keystore.properties")
    if (propFile.exists()) {
        propFile.inputStream().use { load(it) }
    }
}

fun signingSetting(property: String, environment: String): String? =
    keystoreProperties.getProperty(property) ?: System.getenv(environment)

val releaseStoreFile = signingSetting("storeFile", "ANDROID_KEYSTORE_PATH")
val releaseStorePassword = signingSetting("storePassword", "ANDROID_STORE_PASSWORD")
val releaseKeyAlias = signingSetting("keyAlias", "ANDROID_KEY_ALIAS")
val releaseKeyPassword = signingSetting("keyPassword", "ANDROID_KEY_PASSWORD")
val releaseSigningConfigured =
    releaseStoreFile != null &&
        releaseStorePassword != null &&
        releaseKeyAlias != null &&
        releaseKeyPassword != null

